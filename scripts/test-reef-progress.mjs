import assert from 'node:assert/strict';
import { getRouteKey, getActivitySavePrefix } from '../prototype/shared/destinations.mjs';

assert.equal(getRouteKey('lotem', 'reef', 'en'), 'reef-route-lotem-en');
assert.equal(getRouteKey('lotem', 'reef', 'he'), 'reef-route-lotem-he');
assert.equal(getActivitySavePrefix('lotem', 'reef', 'en'), 'reef-lotem-en');

const { isReefUnlocked, openReefRoute, completeReefStage, markReefStorySeen, pendingReefStory } = await import('../prototype/shared/reef-progress.mjs');
const records = new Map();
const storage = { getItem: key => records.get(key) ?? null, setItem: (key, value) => records.set(key, value) };
const profile = { id: 'lotem', name: 'לוטם', learningLanguage: 'en', friend: 'nevet' };
const forestKey = getRouteKey(profile.id, 'forest', 'en');
const forest = JSON.stringify({ currentStage: 36, progress: { 36: 3 }, character: 'nevet' });
assert.equal(isReefUnlocked(profile, storage), false);
assert.throws(() => openReefRoute(profile, storage), /locked/i);
storage.setItem(forestKey, forest);
assert.equal(isReefUnlocked(profile, storage), true);
let route = openReefRoute(profile, storage);
assert.equal(route.currentStage, 1);
assert.equal(pendingReefStory(route).id, 'bridge-forest-reef');
markReefStorySeen(profile, 'bridge-forest-reef', storage);
assert.equal(pendingReefStory(openReefRoute(profile, storage)).id, 'reef-video-01');
markReefStorySeen(profile, 'reef-video-01', storage);
assert.equal(pendingReefStory(openReefRoute(profile, storage)), undefined);
assert.throws(() => completeReefStage(profile, 2, 3, storage), /locked/i);
assert.throws(() => completeReefStage(profile, 1, 4, storage), /stars/i);
for (let id = 1; id <= 36; id++) route = completeReefStage(profile, id, 3, storage);
assert.equal(route.currentStage, 36);
assert.equal(Object.keys(route.progress).length, 36);
assert.equal(route.unlockedVideos.length, 10);
assert.equal(completeReefStage(profile, 5, 1, storage).progress[5], 3);
assert.equal(completeReefStage(profile, 5, 1, storage).unlockedVideos.length, 10);
assert.equal(storage.getItem(forestKey), forest, 'Forest saves must be untouched');
assert.equal(isReefUnlocked({ ...profile, learningLanguage: 'he' }, storage), false);
assert.equal(isReefUnlocked({ ...profile, id: 'tom' }, storage), false);
storage.setItem(forestKey, JSON.stringify({ currentStage: 1, progress: {} }));
assert.equal(isReefUnlocked(profile, storage), true, 'The Reef save retains its earned unlock after a Forest reset');
assert.equal(openReefRoute(profile, storage).seenVideos.includes('bridge-forest-reef'), true);
console.log('PASS: Reef unlock, bridge-once, 36-stage progression, milestones, replays, language/profile isolation and Forest preservation.');
