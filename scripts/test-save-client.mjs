import assert from 'node:assert/strict';
import { createSaveClient } from '../prototype/shared/save-client.mjs';
const values = new Map([['bubble_world_map_progress_v2', '{"lotem":{"currentStage":3}}']]);
const storage = { getItem: k => values.get(k) ?? null, setItem: (k, v) => values.set(k, v) };
const documents = {};
let connected = true;
const fetcher = async (url, options = {}) => {
  if (!connected) throw new TypeError('Offline');
  if (!options.method) return Response.json(documents);
  const key = url.split('/').at(-1);
  const body = JSON.parse(options.body);
  const current = documents[key];
  if ((current?.revision ?? 0) !== body.revision) return Response.json({}, { status: 409 });
  documents[key] = { revision: body.revision + 1, value: body.value };
  return Response.json(documents[key]);
};
const client = createSaveClient({ storage, fetcher });
await client.load();
assert.equal(client.getItem('bubble_world_map_progress_v2'), null, 'old browser progress must not seed cloud saves');
connected = false;
client.setItem('round-lotem', '{"placed":["ball"]}');
await client.flush();
const reopened = createSaveClient({ storage, fetcher });
await reopened.load();
assert.equal(reopened.getItem('round-lotem'), '{"placed":["ball"]}', 'offline pending save survives reload');
connected = true;
await reopened.flush();
assert.equal(documents['round-lotem'].value, '{"placed":["ball"]}');
const second = createSaveClient({ storage: { getItem: () => null, setItem() {} }, fetcher });
await second.load();
assert.equal(second.getItem('round-lotem'), '{"placed":["ball"]}', 'another device receives the saved round');
console.log('PASS: fresh cloud state ignores old progress; offline saves survive reload and sync to another device.');
